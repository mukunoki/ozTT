// 尾崎スキーム I：デバイス上の radix-254 スライサ（INT8 経路．桁を符号-絶対値の UInt8 で出す）
// ---------------------------------------------------------------------------
// 役割：オペランドの各要素を基数 254（桁は ±127）の小整数スライス nslice 本（L+1）に分解し，INT8 行列積が
//       期待する「符号-絶対値」バイトとして出力する．論文の ssec:acc（桁の上限と累積の単位）・ssec:field（INT8 経路の区画）．
//
// 基数と桁の上限は別の量である
//   符号-絶対値バイトの絶対値部が 7 bit しか無いので桁は d = ±127 に収まり，重み
//   （基数）はそこから beta = 2d = 254 と取る．表せる範囲の上限は R = d/(beta-1)
//   = 127/253 で，正規化の目標 T = 1/2 を 0.4% 上回る．この余裕が 1/128 を切るので，
//   ホスト側は最大値の BF16 化を切り上げて |x/tau| <= T を保証する
//   （ozaki1_main.cpp の bf_ceil）．そのうえで残差は |t| <= R に留まり，p 段後の
//   打ち切り誤差は R*beta^-p 以下に落ちる．
//   先行実装 ozIMMU は 2^7 を重みに取り，桁を 7 bit に収める（重み = 桁 + 1）．
//
// 残差を triple-float で持つ理由
//   スライスを 1 本切り出すたびに残差 t = t - d を更新していくが，この残差を
//   FP32 1 本で持つと約 24 bit で飽和し，FP32 2 本（double-single）でも約 48 bit
//   で止まる．FP64 入力の仮数 53 bit を取りこぼさないため，入力値と残差を
//   FP32 3 本組（triple-float，作業精度約 72 bit）で保持する．
//
// 本体（基数倍・丸め・クランプ・残差の更新と持ち回り）は 7 形式のスライサと共有する slice_tf_body.h にある．
// ここは桁 d の符号化（SLICE_SIGNMAG8 = true）だけを決める．出力 c_16 は NSLICE 枚の INT8 符号-絶対値スライス．
//
// 符号-絶対値の符号化
//   スライス値 d のバイト表現は int8( g(d) )，ただし g(d) = (d<0) ? (128-d) : d
//     d=+5   -> g=5    -> uint8 0x05（符号 0，絶対値 5）
//     d=-5   -> g=133  -> uint8 0x85（符号 1，絶対値 5）  ※int8 では -123
//     d=-127 -> g=255  -> uint8 0xFF（符号 1，絶対値 127）
// ホストは OUT_HALF も付けるが，符号-絶対値の出力では効かない（slice_tf_body.h）．

constexpr bool SLICE_SIGNMAG8 = true;    // 桁を符号-絶対値の UInt8 で出す（slice_tf_body.h）
#include "slice_tf_body.h"                // kernel_main

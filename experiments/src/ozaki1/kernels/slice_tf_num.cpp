// 尾崎スキーム I：デバイス上の radix スライサ（INT8 以外の 7 形式で共通．桁の値をそのまま出す）
// ---------------------------------------------------------------------------
// 役割：オペランドの各要素を基数 radix の小整数スライス nslice 本（L+1）に分解し，符号付き
//       整数を GEMM の入力形式（BF16・FP16・FP32・BFP8_b・FP8・BFP4_b・BFP2_b）の値として
//       出力する．論文「尾崎スキーム I」の節．
//       INT8 経路（slice_tf_sm8.cpp）と違い，これらの形式は桁の範囲の整数を無誤差に
//       表せるので，符号-絶対値への符号化は要らない．パッカが DST の FP32 から出力形式へ
//       直接変換する．例外は FP16 で，FP32 の DST から Float16 へのパックが値を壊すため，
//       binary16 のビット列を整数として作って UInt16 で書く（OUT_HALF．sfpu_tf.h の HalfBits）．
//
// 残差を triple-float で持つ理由
//   残差を FP32 1 本で持つと約 24 bit，FP32 2 本でも約 48 bit で飽和する．
//   FP64 入力の仮数 53 bit を取りこぼさないよう，値と残差を FP32 3 本組
//   （triple-float，作業精度約 72 bit）で保持する．
//
// 本体（基数倍・丸め・クランプ・残差の更新と持ち回り）は INT8 のスライサと共有する slice_tf_body.h にある．
// ここは桁 d の出力の形（SLICE_SIGNMAG8 = false）だけを決める．出力 c_16 は NSLICE 枚の符号付き整数スライス．
//
// 基数（桁の重み）と桁の上限は別の量で，既定では重み = 2*桁 である（BF16・BFP8_b は
// 重み 64／桁 ±32，FP8 は 32／±16，BFP4_b は 14／±7，BFP2_b は 2／±1）．クランプは桁の上限で行う．
// 重みを 2*桁 に留めるのは，範囲 R = 桁/(基数-1) が正規化の目標 T を上回る余裕を残すためである（T = 1/2 の形式では
// 桁 32 で 1.6%，桁 16 で 3.2%，桁 7 で 7.7%．BFP2_b は R = T = 1 で，ホストがスケールを切り上げ，さらに
// 最大値より真に大きい 2 のべきに取る．ちょうど T = 1 になる要素は桁 1・残差 1 のまま展開が終わらないため．
// ozaki1_main.cpp の bf_ceil・tau_above）．
// 重みを 2*桁+1 にすると R = T で余裕が 0 になり，BF16 では K が大きいところで到達精度が
// 34.7--40.3 bit まで落ちた（docs/fidelity_radix_sweep.md の 2026-09-21 の追記）．上位 1 語だけを
// 丸めるために d が理想の丸めより 1 大きくなり，残差が R を超えると考えられるが，境界を超える
// 要素の数は測っておらず，原因は特定していない．
// コンパイル時引数の OUT_HALF（oz1_args.h の SC_OUT_HALF）が 1 ならスライスを binary16 のビット列で出す（FP16 経路だけ）．
// DST：HalfBits は term・tmp0・tmp1 を作業に使う（t の 3 本組 acc_hi・acc_mid・acc_lo はパック後に残差として退避するので
// 触らない．名前は sfpu_tf_proc.h の namespace dst）

constexpr bool SLICE_SIGNMAG8 = false;   // 桁の値をそのまま出す（FP16 経路だけ binary16 のビット列．slice_tf_body.h）
#include "slice_tf_body.h"                // kernel_main

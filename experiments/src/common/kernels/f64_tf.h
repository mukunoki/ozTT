#pragma once
//
// FP64 と triple-float を行き来するビット手続き（尾崎スキーム I・II 共通）
// ---------------------------------------------------------------------------
// データ移動カーネル（リーダとライタ）が使う．浮動小数点演算を一切使わないのが
// 要点で，デバイスの RISC-V は FP64 の演算器を持たず（単精度の F 拡張も一部だけで，倍精度の D 拡張は無い．Blackhole の ISA 資料 BabyRISCV/InstructionSet.md），double で書くと soft-float になって
// 大幅に遅くなるためである（倍率は scripts/diagnose/implementation_ratios.sh の ratio_sf_* のログ．スライドの soft-float の頁が引く．
// 論文の本文には soft-float の倍率の節は無い）．
//
//   split_f64          入口：FP64 の 2 語 -> triple-float の 4 つのビット列
//   assemble_tf_f64    出口（scheme I）：3 本 -> FP64．64 bit のアキュムレータ
//   assemble_frac_f64  出口（scheme II）：3 本または 6 本 -> FP64．128 bit の固定小数で
//                      frac を厳密に畳み直してから組み立てる（(-1/2,1/2) の値は変えず，はみ出しを ±1 で戻す．
//                      像は [-1/2,1/2] で，端点の扱いは assemble_frac_f64 の注記）
//
// 出口が 2 つあるのは，集める幅がスキームで違うからである：
//   scheme I  結果そのものを運ぶので 64 bit で足りる
//   scheme II frac は 2^-8 前後の大きさで 2^-99 の絶対精度を保つ必要があり，
//             90 bit を超える幅が要る
// 集めたあと最終スケールを掛けて丸める段（pack_f64）は共通である．
//
// ヘッダはデバイス API に依存しない（<cstdint> だけ）ので，ホスト側からもそのまま
// include できる．tools/tfconv.cpp がこのファイルを直接取り込み，__float128 の
// 参照計算と突き合わせて検査している．
//
// 保証と，保証しないこと
//   ・split は厳密である：hi + mid + lo は x * 2^d に完全に一致する（下の適用範囲内）．
//   ・assemble_* の出力は，limb が窓に収まるかぎり真値を FP64 へ丸めたものから
//     1 ulp 以内である．同点（ちょうど半 ulp）の向きは規定しない：0 から遠い側へ送る．
//     窓に収まらない場合は 1 ulp では収まらない．scheme I は最大指数の limb の先頭ビット
//     から 60 bit 下（その仮数の最下位から 37 bit 下）が窓の底なので，上位 2 本が大きく
//     相殺すると窓の底より下のビットが落ちる（基準が 1 なら 2^-60 までは残り，2^-61 は落ちる）
//     （hi=1, mid=-1+2^-24, lo=2^-61 は 2^-24 を返すが，真値は 2^-24+2^-61）．
//     scheme II も同様で，1 本の limb の中で 2^-124 より下は落ちる（2^-120+2^-143 など）．
//     どちらも落ちる量は「その limb の大きさ」以下である．要素ごとに見ると，
//     相殺後の値に対する相対誤差はいくらでも大きくなりうる．要素単位で 1 ulp を
//     保証したいなら，蓄積を全幅（scheme II なら 192 bit）で持つ必要がある．
//     ノルムに影響しないと言えるのは，出力全体が相殺で小さくならない場合に限る．
//     本稿が測る入力ではそうなっており（selftest.sh と measure/accuracy.sh の到達精度が
//     それを示す），そこでの目標はノルム精度である．出力そのものが大きく相殺する
//     問題に当てはめる場合はこの限りでない．
//     厳密な最近接偶数は実装していない．ここで必要なのは所定の桁範囲，
//     整数GEMMの無誤差条件，CRTの窓条件であり，
//     丸めの同点の向きはこれらの条件を変えない．ModRound は偶数の
//     法で同点が出るが両向きとも同じ剰余類，frac の畳み込みの ±1/2 は窓が狭義
//     なので起きない．同点の向きが答えを変えるのは利用者へ返す FP64 の最下位 1 bit だけで，
//     それを消費する後段は無い．目標は FP64 ネイティブの DGEMM と同等の精度であって，
//     正しい丸めの再現ではない．
//   ・最終スケール W はホストが long double（64 bit 仮数）で求めたもので，丸めの積み上がりは相対で高々，
//     scheme I の radix^-(L+2)（radix を L+2 回割る）が約 (L+2)·2^-64（基数が 2 のべきなら厳密．ozaki1/ozaki1_plan.hpp の
//     recon_scale），scheme II の KM = Π m_i · 2^-2b（法を s-1 回掛ける）が約 (s-1)·2^-64 である（ozaki2_moduli.h の KMl）．
//     FP64 の定数として 1 回掛けると相対 2^-53 が全要素へ一様に乗るのに比べ，既定の構成の上界で約 7〜8 bit 良い
//     （scheme I の INT8 の L+2=9 で 7.8 bit，BFP4_b の L+2=17 で 6.9 bit，scheme II の法 16 本で 7.1 bit．法が増えると減り，
//     24 本で 6.5 bit）．実際の誤差はさらに小さい（254^-9 で 2^-62.5，14^-17 で 2^-63.8）が，元の定数そのものではない．
//
// 適用範囲（呼び出し側が満たすこと）
//   ・入力は有限かつ正規化数の FP64 に限る．非正規化数と 0 は 0 に潰し，Inf/NaN は
//     ここでは検査しない．なおオペランド全体としては，これより狭い制限がスケール算出段に
//     ある：2^128 以上の要素，非零の最大絶対値が 2^-126 未満の行／列，Inf・NaN の要素は同段が検出して
//     止める（common/kernels/scale_f64_reader.cpp の「受け付ける大きさの範囲」）．
//   ・split が厳密だと確かめたのは，正規化後の値 |x·2^d| が 2^-72 以上の範囲である（tools/tfconv.cpp の検査 1 が
//     下げ幅 0〜72 binade で確かめた）．その下で最初に桁を落とすのは下位 limb lo = c·2^elsb（下の split_f64．elsb は
//     仮数の最下位の指数で，値は約 2^(elsb+52)）である：SFPU が FP32 の非正規化数を 0 に潰すなら，c·2^elsb が 2^-126 を
//     下回ったとき（c=1 なら elsb <= -127．正規化後の値 2^-74 未満）に lo から落ちる（潰さないなら lo は非正規化数のまま厳密）．
//     s（と mid = b·s）が 0 になる elsb <= -134，すなわち 2^-81 未満では mid・lo の両方が消える（下の「s の指数」）．
//     2^-126 を下回ると hi も 0 になる．実機の SFPU が非正規化数を潰すかどうかは確かめていないので，保証するのは 2^-72 以上である．
//     binade の数はどれも正規化後の値 1 を基準に数えたもので，最大値からの距離へ読み替えるには寄せる位置を引く：
//     scheme I は行／列の最大値を 1/2 前後（切り捨ての形式で (1/4, (1+2^-7)/2)，BFP2_b は [1/2, 1)）へ寄せるので，
//     2^-72 は最大値から約 70〜72 binade 下である．scheme II は寄せる位置が b と A' の桁数 ND で変わり（ozaki2_main.cpp の
//     指数シフト sh_i = b - 20(ND-1)．最大値は (2^(sh_i-1), 2^sh_i] に来る），最大値からの距離は約 72 + sh_i binade に
//     なる（たとえば b=1・ND=3 では最大値が 2^-39 前後に来るので約 33 binade 下の要素がもう外れ，既定の b=54・ND=3 では約 86）．
//     この範囲は，後段が保持する幅より広い：scheme I のスライスが持つのは行／列の最大値から
//     スライス数 x 1 スライスの bit 数（既定の p で 59〜64 bit）まで，scheme II の整数化は |A'| <= 2^b
//     （既定 b=54）までで，それより下の要素・ビットは既定の設定では保持対象外になり，結果に入らない．
//     保持対象外の要素を無視してよいかは入力の配置で決まり，一般には言えない：行の最大値に比べて小さい
//     要素でも，相手側の対応する要素が大きければ積への寄与は大きい（K=64，各行 A=(1, 2^-127, 0, …)，
//     各列 B=(0, 2^127, 0, …)^T では，どちらの最大値もスケール算出段の範囲の内側で，真値は全要素 1 だが，
//     A の第 2 要素は保持されず結果は 0 になる）．これは行／列ごとのスケールで桁をそろえる方式の精度の
//     制限で，上の項のスケール算出段の範囲の検査（2^128 以上の要素，非零の最大絶対値が 2^-126 未満の
//     行／列）とは別であり，どの段も検出しない．
//   ・出力が FP64 の非正規化数になる場合（|C| < 2^-1022）は ±0 に潰す．入力が
//     すべてゼロのときだけは符号を持たず +0 を返す．
//   ・指数引数（split の d，assemble_* の g）は，通常の正規化が渡す範囲でのみ
//     正しい．elsb = E - 1075 + d と qw + g + ... は int32 で計算するので，桁外れの値を
//     渡すと符号付きオーバーフローになる．同様に limb の FP32 は有限（ee != 255）
//     でなければならず，最終スケール W は最上位ビットが立った正規化仮数
//     （W >= 2^63）でなければならない．違反時の結果は保証しない（W = 0 でも
//     ゼロにはならず，非ゼロ積と同じ経路を通る）．いずれも呼び出し側が満たす条件で，ここでは
//     検査しない（デバイス側は 1 要素ごとに通る経路なので分岐を置かない）．

#include <cstdint>

// FP64 のタイル 1 枚（1024 要素 × 8 B）の大きさ［B］．リーダ・ライタの作業領域の CB（ホストが作る）と，
// カーネルがその中を番地で歩く範囲の両方がこれを使う（両側に 8192 を直書きすると片方だけ変わりうる）
constexpr uint32_t OZ_F64_TILE_BYTES = 1024u * 8u;

// ===========================================================================
// 入口：FP64 の 2 語 -> triple-float の 4 つのビット列
// ===========================================================================
// 下位 2 本の limb は先頭ビット位置の探索（CLZ）なしに組み立てられないので，
// 「マジックナンバ」を足した形で出し，定数の減算と乗算だけを SFPU に任せる
// （slice_tf_core.h の tf_load_f64）：
//   hi    そのまま FP32．a * 2^(elsb+30)（elsb は仮数の最下位の指数．下の split_f64）
//   braw  2^23 + 2^22 + b   （SFPU が 12582912.0f を引く）
//   craw  2^23 + c          （SFPU が  8388608.0f を引く）
//   s     ±2^(elsb+7)       （SFPU が上の 2 つに掛ける．lo は更に 2^-7）
//
// s の指数を 2^elsb ではなく mid の位 2^(elsb+7) に取ってあるのは，s が 0 に落ちる点を
// 7 binade 下げるためである．s = 0 になるのは elsb <= -134，すなわち正規化後の値 1 から（scheme I なら
// 行／列の最大値からおよそ）82 binade 下である．2^elsb に取るとこの点が 75 binade 下まで上がってきて，上に書いた適用範囲
// （確かめた 72 binade）のすぐ隣で s だけが先に落ち，mid/lo の両方が消える．
// なお 7 binade 稼いでも，mid が表せる下限まで届くわけではない：仮数が最大
// （|b| ~ 2^22）の mid は elsb = -155，つまり 103 binade 下まで正規化 FP32 でいられる（数え方は同じ）．
// 揃えるためではなく，適用範囲との間に余裕を作るための 7 である．
// ついでに mid 側の 128 倍が要らなくなる（SFPU の演算が 1 つ減る）．
//
// d は正規化の指数シフト（値を 2^d 倍する）．2 のべきなので無誤差で，FP64 の指数
// フィールドへ整数で足すだけで済む．FP32 の逆数タイルを掛ける必要がなく，スケールが
// FP32 の指数範囲に収まらねばならないという制約も消える．
inline void split_f64(uint32_t w1, uint32_t w0, int32_t d,
                      uint32_t& hi, uint32_t& braw, uint32_t& craw, uint32_t& s) {
    const uint32_t sgn = w1 & 0x80000000u;
    const int32_t  E   = (int32_t)((w1 >> 20) & 0x7FFu);
    if (E == 0) {                       // ゼロと非正規化数は 0 に潰す
        hi = 0u; braw = 0x4B000000u; craw = 0x4B000000u; s = 0u; return;
    }
    // 仮数 S = 2^52 + (w1&0xFFFFF)*2^32 + w0（53 bit）を 30/23/7 bit に割る．
    uint32_t a = 0x400000u | ((w1 & 0x000FFFFFu) << 2) | (w0 >> 30);
    const uint32_t rem = w0 & 0x3FFFFFFFu;
    int32_t r;
    if (rem >= 0x20000000u) { a += 1u; r = (int32_t)rem - 0x40000000; }   // 最近接
    else                    {          r = (int32_t)rem; }
    const int32_t  b = r >> 7;                       // 算術シフト，[-2^22, 2^22-1]
    const uint32_t c = (uint32_t)r & 0x7Fu;          // [0,127]
    const int32_t  elsb = E - 1075 + d;              // 仮数の最下位ビットの指数（スライス数ではない）
    int32_t eh; uint32_t mh;
    if (a == 0x800000u) { eh = elsb + 180; mh = 0u; }   // 丸め上がりで 2^23 になった場合
    else                { eh = elsb + 179; mh = (a << 1) & 0x7FFFFFu; }
    const int32_t es = elsb + 134;                   // 上の「s の指数」を参照
    hi = (eh > 0 && eh < 255) ? (sgn | ((uint32_t)eh << 23) | mh) : 0u;
    s  = (es > 0 && es < 255) ? (sgn | ((uint32_t)es << 23)) : 0u;
    braw = 0x4B000000u | (((uint32_t)(b + 0x400000)) & 0x7FFFFFu);
    craw = 0x4B000000u | c;
}
// 上の s に対して SFPU が掛ける定数（lo を 2^elsb の位へ戻す．mid は s のまま）
constexpr float OZ_TF_LO_SCALE = 0.0078125f;   // 2^-7（2 のべきなので FP32 で厳密）

// ===========================================================================
// 出口の共通部分
// ===========================================================================
// FP32 を（符号付き仮数，指数）へ分解する．非正規化数は 0 に潰す．
inline void dec32(uint32_t u, int32_t& e, int32_t& sig) {
    const int32_t ee = (int32_t)((u >> 23) & 0xFFu);
    if (ee == 0) { e = 0; sig = 0; return; }
    e = ee;
    const int32_t s = (int32_t)(0x800000u | (u & 0x7FFFFFu));
    sig = (u & 0x80000000u) ? -s : s;
}

// A は [2^63, 2^64) に正規化した仮数，W = (Whi:Wlo) は最終スケールの 64 bit 仮数
// （2 のべきでない部分．scheme I は radix^-(L+2)，scheme II は KM）．
// 値は ±A * W * 2^total で，これを FP64 へ丸める（上の「保証」を参照）．
// A と W がどちらも [2^63,2^64) なので積は [2^126,2^128) にあり，上位語 hi の
// 先頭ビットは 62 か 63 にしかない．そのため落とすビット数を 10 か 11 の 2 択に固定できる
// ので，RV32 で重い可変 64 bit シフトの展開が消える．
inline uint64_t pack_f64(uint64_t A, uint32_t Whi, uint32_t Wlo,
                         int32_t total, uint64_t sgn) {
    // A * W：32 bit の掛け算 4 回（RV32 は 64 bit 乗算を持たない）
    const uint32_t a1 = (uint32_t)(A >> 32), a0 = (uint32_t)A;
    const uint64_t p00 = (uint64_t)a0 * Wlo, p01 = (uint64_t)a0 * Whi;
    const uint64_t p10 = (uint64_t)a1 * Wlo, p11 = (uint64_t)a1 * Whi;
    const uint64_t mid = (p00 >> 32) + (uint32_t)p01 + (uint32_t)p10;
    const uint64_t hi  = p11 + (p01 >> 32) + (p10 >> 32) + (mid >> 32);
    const int32_t n = (hi >> 63) ? 63 : 62;
    int32_t exp2 = n + 64 + total;
    // 落とす下位 64 bit は見ない．同点は 0 から遠い側へ送る（上の「保証」を参照）ので，
    // 切り上げるかどうかはガードビット（落とす側の最上位）1 本で決まる．
    uint64_t mant; bool up;
    if (n == 63) { mant = hi >> 11; up = (hi & 0x400ull) != 0; }
    else         { mant = hi >> 10; up = (hi & 0x200ull) != 0; }
    if (up) {
        mant += 1ull;
        if (mant >> 53) { mant >>= 1; exp2 += 1; }
    }
    const int32_t ebias = exp2 + 1023;
    if (ebias <= 0)    return sgn;                            // 非正規化数は ±0 に潰す
    if (ebias >= 2047) return sgn | 0x7FF0000000000000ull;    // オーバーフロー -> ±inf
    return sgn | ((uint64_t)ebias << 52) | (mant & 0x000FFFFFFFFFFFFFull);
}

// ===========================================================================
// 出口（scheme I）：triple-float の 3 本 -> FP64
// ===========================================================================
// sig * 2^sh を返す．窓の下へ落ちきったら 0（呼び出し側はこの 0 を見て，値があるのに
// 寄与しなかった limb を見分ける）．負の符号付き整数の左シフトは C++17 で未定義なので，
// unsigned で寄せてから符号付きへ戻す（GCC ではモジュロ変換で期待どおり）．
// 切り捨ては符号によらず 0 方向へ行う：算術右シフト（-inf 方向）だと負の項だけ
// 絶対値が切り上がり，符号で挙動が変わってしまうためである．
inline int64_t acc64_term(int32_t sig, int32_t sh) {
    if (!sig) return 0;
    if (sh >= 0)   return (int64_t)((uint64_t)(int64_t)sig << sh);
    if (sh <= -32) return 0;
    const uint32_t n = (uint32_t)(-sh);
    const int32_t  m = (sig < 0) ? -sig : sig;     // |sig| < 2^24 なので符号反転は安全
    const int64_t  q = (int64_t)(m >> n);
    return (sig < 0) ? -q : q;
}

// 3 本のうち最大の指数を基準にし，そこから 37 bit 左へ寄せて集める．
// 37 なのは桁溢れを防ぐためである：再構成の出力は必ずしも正準な 3 本組
// （|mid| <= ulp(hi)/2）ではなく，中位が上位と同じ位に来ることがある．39 で寄せると
// 3 本の和が int64 を越えて符号が反転する（7040^3 の FP8 で実際に 1 要素だけ起きた）．
// 37 なら各項が 2^61 未満なので 3 本足しても安全で，丸め位置の下にはまだ 8 bit の
// 余裕が残る．
//
// 窓の底は基準 limb の先頭ビットから 60 bit 下で，それより下のビットは落ちる
// （acc64_term の sh<=-32 は元の limb の指数差ではなく，この窓の中のシフト量である）．
// 上位 2 本がほぼ相殺すると，返す値と真値の差は「落ちたビットの大きさ」で，相殺後の値に
// 対しては 1 ulp を大きく超えうる（上の「保証」に例を挙げた）．元の上位 limb に対しては
// 2^-58 倍未満（3 本それぞれ窓の底 1 単位未満）なので，
// 出力全体が相殺で小さくならないかぎりノルムには影響しない．その条件は冒頭の
// 「保証と，保証しないこと」に書いたとおりで，本稿が測る入力では成り立っている．
// なお全部が落ちて acc が 0 になる場合だけは，下の再収集が拾う．
inline uint64_t assemble_tf_f64(uint32_t hb, uint32_t mb, uint32_t lb, int32_t g,
                                uint32_t Whi, uint32_t Wlo, int32_t qw) {
    int32_t eh, em, el, gh, gm, gl;               // g* は符号付き仮数
    dec32(hb, eh, gh); dec32(mb, em, gm); dec32(lb, el, gl);
    if (gh == 0 && gm == 0 && gl == 0) return 0ull;
    int32_t ebase = eh;
    if (em > ebase) ebase = em;
    if (el > ebase) ebase = el;
    const int64_t ch = acc64_term(gh, eh - ebase + 37);
    const int64_t cm = acc64_term(gm, em - ebase + 37);
    const int64_t cl = acc64_term(gl, el - ebase + 37);
    int64_t acc = ch + cm + cl;
    // 窓に残せた limb が相殺して 0 になり，しかも窓の下へ落ちた limb がある場合．
    // そのまま 0 を返すと，真値が落とした limb そのものなのに 0 になってしまう
    // （例：hi=1, mid=-1, lo=2^-70）．相殺した側の寄与は 0 なので，窓に残せた
    // limb を消し，残りだけで基準を取り直して集め直す．
    if (acc == 0) {
        if (ch) { eh = 0; gh = 0; }              // 寄与した limb は相殺しきっている
        if (cm) { em = 0; gm = 0; }
        if (cl) { el = 0; gl = 0; }
        if (gh == 0 && gm == 0 && gl == 0) return 0ull;   // 真に 0
        ebase = eh; if (em > ebase) ebase = em; if (el > ebase) ebase = el;
        acc = acc64_term(gh, eh - ebase + 37)
            + acc64_term(gm, em - ebase + 37)
            + acc64_term(gl, el - ebase + 37);
    }
    if (acc == 0) return 0ull;
    const uint64_t sgn = (acc < 0) ? 0x8000000000000000ull : 0ull;
    uint64_t A = (acc < 0) ? (uint64_t)(-acc) : (uint64_t)acc;
    // 64 bit へ正規化．デバイスの RISC-V は Zbb の clz を持つので，1 bit ずつ寄せる
    // ループではなく先頭 0 の数を 1 命令で数える（結果はビット単位で同一である）．
    // acc != 0 は直前で確かめてあるので clz の未定義域には入らない．
    const int32_t shA = __builtin_clzll(A); A <<= shA;
    return pack_f64(A, Whi, Wlo, qw + g + (ebase - 187) - shA, sgn);
}

// ===========================================================================
// 出口（scheme II）：frac の 3 本（1 パス）または 6 本（2 パス）-> FP64
// ===========================================================================
// acc = frac * 2^124 の 128 bit 固定小数（4 語，w[0] が最下位）に集める．limb の
// 指数 e に対しシフト量は e-26 で，上端 2^-1 の limb でも 2^124 を越えず，下端
// 2^-97 の limb も 1 bit も落ちない．
struct A128 { uint32_t w[4]; };
// 128 bit 固定小数のタイル 1 枚（1024 要素 × 16 B）の大きさ［B］．尾崎 II の 2 パス構成の第 1 パスが書き，最終パスが
// 読む DRAM のページと L1 の作業領域（recon_writer.cpp・recon_reader.cpp と ozaki2_main.cpp の run_recon_pass）
constexpr uint32_t OZ_A128_TILE_BYTES = 1024u * (uint32_t)sizeof(A128);
static_assert(sizeof(A128) == 16, "A128 は 4 語の 128 bit 固定小数");
inline void a128_add(A128& a, int32_t k, uint32_t v) {
    for (; k < 4 && v; ++k) { const uint32_t o = a.w[k]; a.w[k] = o + v; v = (a.w[k] < o); }
}
inline void a128_sub(A128& a, int32_t k, uint32_t v) {
    for (; k < 4 && v; ++k) { const uint32_t o = a.w[k]; a.w[k] = o - v; v = (o < v); }
}
inline void a128_term(A128& a, int32_t sig, int32_t sh) {   // acc += sig * 2^sh
    if (!sig || sh <= -24) return;               // 仮数が丸ごと固定小数の最下位より下
    const bool     neg = sig < 0;
    const uint64_t m   = (uint64_t)(neg ? -(int64_t)sig : (int64_t)sig);
    // sh < 0 は最下位より下にはみ出す分を落として残りを足す（w は 0 のまま，
    // m < 2^24 なので上位語は 0 になり，そちらの加減算は空回りする）．
    const uint64_t v = (sh < 0) ? (m >> (uint32_t)(-sh)) : (m << (sh & 31));
    const int32_t  w = (sh < 0) ? 0 : (sh >> 5);
    if (!v) return;
    if (neg) { a128_sub(a, w, (uint32_t)v); a128_sub(a, w + 1, (uint32_t)(v >> 32)); }
    else     { a128_add(a, w, (uint32_t)v); a128_add(a, w + 1, (uint32_t)(v >> 32)); }
}

// limb nl 本を 128 bit 固定小数 a に足す（acc = 値 * 2^124）．項ごとに最下位より下を落とすので，
// 足す順序や，limb を何回かに分けて足すことに依らず同じ値になる（2 パス構成の第 1 パスが自分の 3 本を
// 先に固定小数へ足しておき，第 2 パスが残りの 3 本を足すのは，6 本をまとめて足すのとビット単位で同じ）．
inline void a128_add_limbs(A128& a, const uint32_t* limb, uint32_t nl) {
    for (uint32_t i = 0; i < nl; i++) {
        int32_t e, sig; dec32(limb[i], e, sig);
        a128_term(a, sig, e - 26);
    }
}

inline uint64_t a128_frac_to_f64(A128 a, int32_t g, uint32_t Whi, uint32_t Wlo, int32_t qw);

inline uint64_t assemble_frac_f64(const uint32_t* limb, uint32_t nl,
                                  int32_t g, uint32_t Whi, uint32_t Wlo, int32_t qw) {
    A128 a{{0, 0, 0, 0}};
    a128_add_limbs(a, limb, nl);
    return a128_frac_to_f64(a, g, Whi, Wlo, qw);
}

// 集めた固定小数 a（frac * 2^124）を畳み，KM * 2^g を掛けた FP64 にする
inline uint64_t a128_frac_to_f64(A128 a, int32_t g, uint32_t Whi, uint32_t Wlo, int32_t qw) {
    // 契約上の frac は (-1/2,1/2) の開区間にあり，そこへ固定小数のまま厳密に畳み直す．
    // 1 パス構成でも 2 パス構成でも必ずここで畳む：
    //   ・計算カーネル（ozaki2/kernels/recon_crt.cpp）は法ごとに a0 -= round(a0) を行うだけで，3 本組の値は
    //     [-1/2,1/2] から a1 + a2 だけはみ出しうる．これをカーネルの FP32 で畳もうとする（fl(a0+a1) で
    //     判定して a0 に ±1）と，2^-25 程度より細かいはみ出しを見逃し（a0 = -1/2 ちょうどに a1 = -2^-30 が
    //     乗ると真の frac 1/2 - 2^-30 から 1 ずれたまま出て，C が M*2^-2b*tau_A*tau_B 違う），a0 が (1/4,1/2)
    //     のときの a0 - 1 も FP32 では厳密でない（frac が 2^-25 丸まる）．窓の条件（ozaki2_moduli.h の
    //     OZ2_WIN_EPS）が保証する余白は 1/2 - |frac| >= 約 2^-31.4 しかないので，窓の端の要素では
    //     どちらも起こりうる（tools/crt_fold_check.cpp が本番の演算列の FP32 模擬で確かめる）．
    //     128 bit の固定小数（最下位 2^-124）なら余白より十分細かく，1 の足し引きも厳密である．
    //   ・2 パス構成では 2 つのパスの和をまとめて畳む．
    // 入力の limb の和は (-3/2, 3/2) にある（各パスの値は [-1/2,1/2] から高々 2^-18 程度はみ出すだけ）ので，
    // 1 を 1 回足すか引くかで足りる．規則は f -= roundq(f) と同じである（tools/tfconv.cpp の参照計算も
    // この規則で突き合わせる）．roundq は 0 から遠い側へ送るので ±1/2 ちょうどは入れ替わる
    // （+1/2 -> -1/2，-1/2 -> +1/2）が，CRT の窓は狭義（|C'| < M/2）なので frac が ±1/2 ちょうどになることは
    // 原理的に無く，端点の扱いは参照計算との一致のためだけである．(-1/2,1/2) の内側の値は変えない．
    // 1.0 は 2^124，すなわち w[3] のビット 28 にあたる．
    // 1 要素ごとに通る経路なので，ふつうの要素（|値| < 1/2 で，上位語が -2^27 ちょうどでもない）は
    // 符号なしの比較 1 回と等値比較 1 回で素通りさせ，畳む判定はまれな側でだけ行う
    // （top + 2^27 を符号なしで見て 2^28 以上 ⟺ top が [-2^27, 2^27) の外．top = -2^27 は値が
    // -1/2 以上 -1/2 + 2^-28 未満で，下位語がすべて 0 のときだけ -1/2 ちょうどとして +1 する）．
    {
        const uint32_t top = a.w[3];
        if (top + 0x08000000u >= 0x10000000u || top == 0xF8000000u) {
            if ((int32_t)top >= 0x08000000) a128_sub(a, 3, 0x10000000u);
            else if ((int32_t)top < -0x08000000 || (a.w[0] | a.w[1] | a.w[2]) == 0u)
                a128_add(a, 3, 0x10000000u);
        }
    }
    const bool neg = (a.w[3] & 0x80000000u) != 0;
    if (neg) { for (int32_t i = 0; i < 4; i++) a.w[i] = ~a.w[i]; a128_add(a, 0, 1u); }
    if (!(a.w[0] | a.w[1] | a.w[2] | a.w[3])) return 0ull;
    // 先頭の 0 ビット数．語の走査は高々 3 周なのでそのままにし，語の中は clz で数える
    // （上の全零判定を通っているので a.w[3-wsh] != 0 が保証される）．
    int32_t wsh = 0; while (a.w[3 - wsh] == 0) wsh++;
    const int32_t lz = 32 * wsh + __builtin_clz(a.w[3 - wsh]);
    uint64_t A;
    if (lz <= 64) {                                   // 上位 64 bit を取り出す
        // k <= 2．off != 0 なら 64-lz は 32 の倍数でないので k <= 1 で，a.w[k+2] は範囲内．
        const int32_t k = (64 - lz) >> 5, off = (64 - lz) & 31;
        A = (((uint64_t)a.w[k + 1] << 32) | a.w[k]) >> off;
        if (off) A |= (uint64_t)a.w[k + 2] << (64 - off);
    } else {
        A = (((uint64_t)a.w[1] << 32) | a.w[0]) << (lz - 64);
    }
    // 値 = ±A * 2^(-lz-60)
    return pack_f64(A, Whi, Wlo, qw + g - lz - 60,
                    neg ? 0x8000000000000000ull : 0ull);
}
